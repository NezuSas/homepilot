// Generates docs/design-system-catalog.md from the code, so the design catalog that feeds
// Figma (tokens, type scale, components, variants) can never drift from the implementation.
//   node scripts/generate-design-catalog.mjs          write the file
//   node scripts/generate-design-catalog.mjs --check  fail if the file is out of date
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import ts from 'typescript';

const root = process.cwd();
const checkOnly = process.argv.includes('--check');
const consoleDir = join(root, 'apps', 'operator-console');
const uiDir = join(consoleDir, 'src', 'components', 'ui');
const outPath = join(root, 'docs', 'design-system-catalog.md');

const css = readFileSync(join(consoleDir, 'src', 'index.css'), 'utf8');
const tailwind = readFileSync(join(consoleDir, 'tailwind.config.js'), 'utf8');

/** First declaration of each custom property inside the dark (:root) and light (.light) blocks. */
function readTokens() {
  const dark = new Map();
  const light = new Map();
  let target = null;
  for (const line of css.split(/\r?\n/)) {
    if (/^\s*:root\b[^{]*\{/.test(line)) target = dark;
    else if (/^\s*\.light\b[^{]*\{/.test(line)) target = light;
    else if (/^\s*\}/.test(line) && !/^\s{3,}/.test(line)) target = null;
    const match = target && line.match(/^\s*--([a-z0-9-]+):\s*([^;]+);/);
    if (match && !target.has(match[1])) target.set(match[1], match[2].replace(/\/\*.*?\*\//g, '').trim());
  }
  return { dark, light };
}

const colorTokens = ['background', 'foreground', 'card', 'card-foreground', 'popover', 'muted', 'muted-foreground', 'border', 'border-subtle',
  'primary', 'primary-foreground', 'success', 'warning', 'danger', 'button-primary', 'button-secondary', 'button-danger'];
const shapeTokens = ['radius', 'radius-control', 'radius-card', 'radius-panel', 'radius-modal', 'radius-pill'];

function typeScale() {
  const rows = [];
  for (const match of tailwind.matchAll(/^\s*(?:'([a-z0-9-]+)'|([a-z0-9]+)):\s*\['([^']+)',\s*\{\s*lineHeight:\s*'([^']+)'/gm)) {
    const name = match[1] ?? match[2];
    if (/fluid/.test(name)) continue;
    rows.push({ name, size: match[3], lineHeight: match[4] });
  }
  return rows;
}

function docPurpose(name) {
  const docPath = join(root, 'docs', 'components', `${name}.md`);
  if (!existsSync(docPath)) return '';
  const text = readFileSync(docPath, 'utf8').replace(/\r/g, '');
  const match = text.match(/## Purpose\s+([\s\S]*?)(?:\n## |\n*$)/);
  return match ? match[1].trim().replace(/\s+/g, ' ') : '';
}

/** Props whose type is a union of string literals: those are the component variants. */
function readVariants(file) {
  const source = ts.createSourceFile(file, readFileSync(file, 'utf8'), ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
  const variants = [];
  const visit = (node) => {
    if (ts.isInterfaceDeclaration(node) && /Props$/.test(node.name.text)) {
      for (const member of node.members) {
        if (!ts.isPropertySignature(member) || !member.type || !ts.isUnionTypeNode(member.type)) continue;
        const literals = member.type.types.filter((type) => ts.isLiteralTypeNode(type) && ts.isStringLiteral(type.literal)).map((type) => type.literal.text);
        if (literals.length >= 2 && literals.length === member.type.types.length) variants.push({ prop: member.name.getText(source), values: literals });
      }
    }
    ts.forEachChild(node, visit);
  };
  visit(source);
  return variants;
}

const components = readdirSync(uiDir)
  .filter((name) => /\.tsx$/.test(name) && !/\.test\.tsx$/.test(name))
  .map((name) => name.replace(/\.tsx$/, ''))
  .sort((a, b) => a.localeCompare(b));

const { dark, light } = readTokens();
const lines = [];
lines.push('# Operator Console Design System Catalog');
lines.push('');
lines.push('> Generated by `node scripts/generate-design-catalog.mjs` from the code. Do not edit by hand:');
lines.push('> change the component or token and regenerate. Figma mirrors this file: one style or variable per');
lines.push('> token row, one component per section, one variant property per row of the variants table.');
lines.push('');
lines.push('## Colour tokens');
lines.push('');
lines.push('| Token | Dark | Light |');
lines.push('| --- | --- | --- |');
for (const token of colorTokens) lines.push(`| \`${token}\` | ${dark.get(token) ?? '–'} | ${light.get(token) ?? '–'} |`);
lines.push('');
lines.push('## Shape tokens');
lines.push('');
lines.push('| Token | Value |');
lines.push('| --- | --- |');
for (const token of shapeTokens) lines.push(`| \`${token}\` | ${dark.get(token) ?? '–'} |`);
lines.push('');
lines.push('## Type scale');
lines.push('');
lines.push('| Style | Size | Line height |');
lines.push('| --- | --- | --- |');
for (const row of typeScale()) lines.push(`| \`text-${row.name}\` | ${row.size} | ${row.lineHeight} |`);
lines.push('');
lines.push('## Components');
lines.push('');
lines.push(`${components.length} shared components in \`apps/operator-console/src/components/ui\`.`);
for (const name of components) {
  const variants = readVariants(join(uiDir, `${name}.tsx`));
  const purpose = docPurpose(name);
  lines.push('');
  lines.push(`### ${name}`);
  lines.push('');
  lines.push(purpose || '_No purpose documented._');
  lines.push('');
  lines.push(`Source: \`components/ui/${name}.tsx\`${existsSync(join(root, 'docs', 'components', `${name}.md`)) ? ` · Doc: \`docs/components/${name}.md\`` : ''}`);
  if (variants.length > 0) {
    lines.push('');
    lines.push('| Variant property | Values |');
    lines.push('| --- | --- |');
    for (const variant of variants) lines.push(`| \`${variant.prop}\` | ${variant.values.map((value) => `\`${value}\``).join(', ')} |`);
  }
}
lines.push('');

const output = lines.join('\n');
if (checkOnly) {
  const current = existsSync(outPath) ? readFileSync(outPath, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== output) {
    console.error('docs/design-system-catalog.md is out of date: run `node scripts/generate-design-catalog.mjs`.');
    process.exit(1);
  }
  console.log(`Design catalog is up to date (${components.length} components).`);
} else {
  writeFileSync(outPath, output);
  console.log(`Design catalog written: ${components.length} components, ${colorTokens.length} colour tokens.`);
}
